"""
build_evidence.py
-----------------
The **evidence compiler**: the core of the Stage-3 framework. It reads the
machine artefacts Stages 0-2 actually produced, generation manifests,
metrics, membership-inference results, and compiles them into the
audit-facing evidence package:

    doc/evidence/DPIA.md                    (ICO-structured impact assessment)
    doc/evidence/data-card.md               (Datasheets for Datasets)
    doc/evidence/model-card.md              (Model Cards for Model Reporting)
    doc/evidence/risk-register.md           (residual risks, owners, status)
    doc/evidence/regulatory-mapping.md      (evidence -> ICO / GDPR / EU AI Act)

Design rule: every number in the evidence package is INJECTED from pipeline
artefacts, never hand-typed, compliance documents drift unless they are
generated by the same pipeline that generated the data. Templates live in
doc/templates/ with {{PLACEHOLDER}} slots; re-running the compiler after any
upstream re-run refreshes the whole package. Reusing the framework on another
dataset (e.g. eICU-CRD) means pointing config.yaml at that dataset's
artefacts.
"""
from __future__ import annotations

import argparse
import json
import os

import yaml

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _load(path):
    with open(path) as f:
        return json.load(f)


def _fmt(x, nd=3):
    return "n/a" if x is None else f"{x:.{nd}f}"


def gather(cfg):
    """Pull every injected value from the upstream artefacts."""
    s0m, s1m, s2m = (_load(cfg[k]) for k in
                     ("stage0_manifest", "stage1_manifest", "stage2_manifest"))
    r0, r1, r2 = (_load(cfg[k]) for k in
                  ("stage0_metrics", "stage1_metrics", "stage2_metrics"))

    arm = "fairsample"                      # canonical Stage-2 release arm
    los2, rd2 = s2m["datasets"]["los"], s2m["datasets"]["readmission"]
    mia = r2["mia"]
    rep = r2["readmission"][arm]["representation"]["insurance"]
    rep_base = r2["readmission"]["dpbaseline"]["representation"]["insurance"]

    v = {
        "GEN_DATE": s2m.get("generated", "2026-07-12"),
        "EPS_LOS": _fmt(los2["arms"][arm]["epsilon_spent"], 2),
        "EPS_READM": _fmt(rd2["arms"][arm]["epsilon_spent"], 2),
        "DELTA": "1e-5", "DELTA_BED": "1e-4",
        "SIGMA_TAB": _fmt(los2["arms"][arm]["sigma"], 2),
        "N_LOS": f"{los2['arms'][arm]['n_synthetic']:,}",
        "N_READM": f"{rd2['arms'][arm]['n_synthetic']:,}",
        "SENSITIVE": "gender; insurance (readmission), gender (LOS)",
        "MIA_LOS_DCR": _fmt(mia["los"]["attack_auc_dcr"]),
        "MIA_LOS_KNN": _fmt(mia["los"]["attack_auc_knn_classifier"]),
        "MIA_RD_DCR": _fmt(mia["readmission"]["attack_auc_dcr"]),
        "MIA_RD_KNN": _fmt(mia["readmission"]["attack_auc_knn_classifier"]),
        "NEARDUP_LOS": _fmt(mia["los"]["near_duplicate_share@0.1"]),
        "NEARDUP_RD": _fmt(mia["readmission"]["near_duplicate_share@0.1"]),
        "UTIL_TRTR_RD": _fmt(r2["readmission"]["TRTR"]["roc_auc"]),
        "UTIL_S0_RD": _fmt(r2["readmission"]["stage0"]["roc_auc"]),
        "UTIL_REL_RD": _fmt(r2["readmission"][arm]["roc_auc"]),
        "UTIL_TRTR_LOS": _fmt(r2["los"]["TRTR"]["r2"]),
        "UTIL_S0_LOS": _fmt(r2["los"]["stage0"]["r2"]),
        "UTIL_REL_LOS": _fmt(r2["los"][arm]["r2"]),
        "REP_MEDICARE_REAL": _fmt(rep["Medicare"]["real"]),
        "REP_MEDICARE_BASE": _fmt(rep_base["Medicare"]["dataset"]),
        "REP_MEDICARE_REL": _fmt(rep["Medicare"]["dataset"]),
        "REP_MEDICAID_REAL": _fmt(rep["Medicaid"]["real"]),
        "REP_MEDICAID_REL": _fmt(rep["Medicaid"]["dataset"]),
        "CTGAN_EPOCHS": str(s2m["ctgan"]["epochs"]),
        "CTGAN_FITROWS": f"{s2m['ctgan']['max_train_rows']:,}",
        "GENERATOR": s2m["generator"],
        "CANONICAL_ARM": arm,
    }
    v.update(multiseed(cfg, arm))
    return v


def _ci(d, nd=3):
    return f"{d['mean']:.{nd}f} ± {d['ci95_half_width']:.{nd}f}"


def _mde(a, b):
    """Minimum detectable paired effect at alpha 0.05, power 0.8 (the
    evidence repository's definition)."""
    import numpy as np
    from scipy import stats
    d = np.asarray(a, float) - np.asarray(b, float)
    df = len(d) - 1
    return float((stats.t.ppf(0.975, df) + stats.t.ppf(0.8, df))
                 * d.std(ddof=1) / np.sqrt(len(d)))


def multiseed(cfg, arm):
    """Five-seed context from the evidence repository. The released dataset
    is one training run (seed 42); because differential privacy makes runs
    unpredictable, the evidence package reports the recipe's mean and 95%
    interval across seeds beside the released run's own values."""
    m = _load(cfg["multiseed_metrics"])
    t = m["tasks"]
    v = {"MS_N": str(m["n_seeds"])}
    for task, key, tag in (("readmission", "roc_auc", "RD"),
                           ("los", "r2", "LOS")):
        v[f"MS_TRTR_{tag}"] = _ci(t[task]["TRTR"][key])
        v[f"MS_S0_{tag}"] = _ci(t[task]["stage0"][key])
        v[f"MS_REL_{tag}"] = _ci(t[task][arm][key])
        s0 = t[task]["stage0"][key]["values"]
        v[f"MS_S0_{tag}_MIN"] = _fmt(min(s0))
        v[f"MS_S0_{tag}_MAX"] = _fmt(max(s0))
        v[f"NOISE_FLOOR_{tag}"] = _fmt(_mde(t[task]["stage1"][key]["values"],
                                            t[task]["dprepeat"][key]["values"]))
    seeds = sorted(os.listdir(cfg["multiseed_seeds"]))
    shares = {"base": [], "rel": []}
    for f in seeds:
        if not f.startswith("seed_"):
            continue
        rep = _load(os.path.join(cfg["multiseed_seeds"], f))[
            "tasks"]["readmission"]["representation"]
        shares["base"].append(rep["dpbaseline"]["insurance"]["Medicare"]
                              ["dataset"])
        shares["rel"].append(rep[arm]["insurance"]["Medicare"]["dataset"])
    import numpy as np
    from scipy import stats
    for k, vals in shares.items():
        a = np.asarray(vals)
        half = stats.t.ppf(0.975, len(a) - 1) * a.std(ddof=1) / np.sqrt(len(a))
        v[f"MS_MEDICARE_{k.upper()}"] = f"{a.mean():.3f} ± {half:.3f}"
    v["SEED_NOISE"] = (f"minimum detectable paired effect at {v['MS_N']} "
                       f"seeds: {v['NOISE_FLOOR_RD']} ROC-AUC / "
                       f"{v['NOISE_FLOOR_LOS']} R² (independent DP "
                       "replicates, evidence repository)")
    return v


def render(cfg):
    values = gather(cfg)
    tdir = os.path.join(HERE, "doc", "templates")
    edir = os.path.join(HERE, "doc", "evidence")
    os.makedirs(edir, exist_ok=True)
    missing = set()
    for name in sorted(os.listdir(tdir)):
        if not name.endswith(".md"):
            continue
        with open(os.path.join(tdir, name)) as f:
            text = f.read()
        for k, val in values.items():
            text = text.replace("{{" + k + "}}", str(val))
        if "{{" in text:
            for tok in {t.split("}}")[0] for t in text.split("{{")[1:]}:
                missing.add(f"{name}:{tok}")
        out = os.path.join(edir, name.replace("-template", ""))
        with open(out, "w") as f:
            f.write(text)
        print(f"wrote {out}", flush=True)
    if missing:
        raise SystemExit(f"unfilled placeholders: {sorted(missing)}")
    with open(os.path.join(HERE, "results", "evidence_values.json"), "w") as f:
        json.dump(values, f, indent=2)
    print("evidence package compiled; all placeholders filled.", flush=True)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=os.path.join(HERE, "config.yaml"))
    args = ap.parse_args()
    with open(args.config) as f:
        render(yaml.safe_load(f))
